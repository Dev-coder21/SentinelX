import { useRef } from 'react'
import { useEnter } from '../ui'

/* Results of `python -m evaluation.backtest` (backend/evaluation/results).
   Each tier row is [supplier, peak, +14 days, +28 days]. */
const CASES: { full: string; yr: number; type: string; T: ([string, number, number, number] | null)[] }[] = [
  { full: 'Suez Canal obstruction', yr: 2021, type: 'Logistics', T: [['Eindhoven Litho Circuits', 92.2, 41.7, 20.9], ['Bavaria Sensor Dynamics', 78.0, 35.3, 17.7], ['Nordic Green Packaging', 63.8, 28.9, 14.4]] },
  { full: 'Red Sea chokepoint crisis', yr: 2024, type: 'Geopolitical', T: [['Eindhoven Litho Circuits', 76.3, 32.2, 19.6], ['Bavaria Sensor Dynamics', 64.6, 27.2, 16.6], ['Nordic Green Packaging', 52.8, 22.3, 13.6]] },
  { full: 'Typhoon Gaemi', yr: 2024, type: 'Weather', T: [['Pacific Silicon Foundry', 100, 52.8, 26.4], null, ['Tokyo Nano-Capacitors', 75.9, 36.6, 18.3]] },
  { full: 'US East and Gulf Coast port strike', yr: 2024, type: 'Labor', T: [['Silicon Valley RF Labs', 100, 73.1, 40.3], ['Austin Power Systems', 100, 61.8, 34.1], ['Monterrey Polymer Enclosures', 82.5, 50.6, 27.9]] },
]

const sstep = (a: number, b: number, x: number) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t) }
function caseValue(T1: [string, number, number, number], d: number) {
  const [, pk, v14, v28] = T1
  if (d < -2) return 0
  if (d < 0) return pk * sstep(-2, 0, d)
  if (d <= 14) return pk * Math.pow(v14 / pk, d / 14)
  if (d <= 28) return v14 * Math.pow(v28 / v14, (d - 14) / 14)
  return v28
}

export function ValidationPage() {
  const ref = useRef<HTMLDivElement>(null)
  useEnter(ref, 'validation')
  const cols = ['#D93A12', '#DE9E00', '#1F3BFF']
  const X = (d: number) => 40 + ((d + 4) / 36) * 560, Y = (v: number) => 170 - v * 1.5
  return (
    <div className="pgi" ref={ref}>
      {CASES.map((c) => (
        <div key={c.full} className="c s6">
          <div className="ch-h"><h3>{c.full}, {c.yr}</h3><span className="small">{c.type}</span></div>
          <svg className="chart" viewBox="0 0 640 196" role="img" aria-label={`${c.full} score curves`}>
            {[0, 50, 100].map((v) => <g key={v}><line x1="40" x2="600" y1={Y(v)} y2={Y(v)} stroke="rgba(20,22,28,.08)" /><text x="32" y={Y(v) + 4} fontSize="11" textAnchor="end" fill="#5B5E66">{v}</text></g>)}
            {[0, 14, 28].map((d) => <g key={d}><line x1={X(d)} x2={X(d)} y1={Y(100)} y2={Y(0)} stroke="rgba(20,22,28,.12)" strokeDasharray="2 3" /><text x={X(d)} y="190" fontSize="11" textAnchor="middle" fill="#5B5E66">{d === 0 ? 'peak' : `+${d} days`}</text></g>)}
            {c.T.map((t, k) => {
              if (!t) return null
              let dd = ''
              for (let d = -4; d <= 32; d += 0.5) dd += (d === -4 ? 'M' : 'L') + X(d).toFixed(1) + ' ' + Y(caseValue(t, d)).toFixed(1)
              return <g key={k}><path d={dd} fill="none" stroke={cols[k]} strokeWidth="2" /><text x={X(32) + 6} y={Y(caseValue(t, 32)) + 4} fontSize="11" fill="#14161C">T{k + 1}</text></g>
            })}
          </svg>
          <div className="legend">{c.T.map((t, k) => t ? <span key={k}><i style={{ background: cols[k] }} />T{k + 1} {t[0]}, peak {t[1]}</span> : <span key={k} className="small">No Tier 2 supplier exposed</span>)}</div>
        </div>
      ))}
      <div className="c s12" style={{ overflowX: 'auto' }}>
        <div className="ch-h"><h3>All tiers</h3><span className="small">Score at the peak, then 14 and 28 days later</span></div>
        <table className="tblx" style={{ minWidth: 760 }}>
          <thead><tr><th>Case</th><th>Representative supplier</th><th>Tier</th><th className="r">Peak</th><th className="r">+14 days</th><th className="r">+28 days</th></tr></thead>
          <tbody>{CASES.flatMap((c) => c.T.map((t, k) => t && (
            <tr key={c.full + k} style={{ cursor: 'default' }}><td>{k === 0 ? <><b>{c.full}</b><br /><span className="small">{c.yr}, {c.type.toLowerCase()}</span></> : null}</td><td>{t[0]}</td><td><span className="tier">T{k + 1}</span></td><td className="r">{t[1].toFixed(1)}</td><td className="r">{t[2].toFixed(1)}</td><td className="r">{t[3].toFixed(1)}</td></tr>
          )))}</tbody>
        </table>
      </div>
      <p className="small s12" style={{ margin: 0 }}>Retrospective behavioural validation of the scoring pipeline, generated by <code>python -m evaluation.backtest</code>. It checks the scorer reacts to real events as designed and does not claim predictive accuracy.</p>
    </div>
  )
}
